    `assignee_ids` VARCHAR(500) DEFAULT NULL COMMENT '审批人IDs（逗号分隔）',
    `role_ids` VARCHAR(500) DEFAULT NULL COMMENT '审批角色IDs',
    `dept_level` INT DEFAULT NULL COMMENT '部门级别',
