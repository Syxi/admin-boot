    `definition_id` BIGINT NOT NULL COMMENT '流程定义ID',
    `node_id` VARCHAR(100) NOT NULL COMMENT '节点ID',
    `node_name` VARCHAR(200) DEFAULT NULL COMMENT '节点名称',
