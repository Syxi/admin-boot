-- ============================================================
-- Flowable 工作流模块数据库表结构
-- ============================================================

-- 流程定义表
CREATE TABLE IF NOT EXISTS `workflow_definition` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    `process_key` VARCHAR(100) NOT NULL COMMENT '流程定义Key',
    `process_name` VARCHAR(200) NOT NULL COMMENT '流程名称',
    `category` VARCHAR(100) DEFAULT NULL COMMENT '流程分类',
    `description` VARCHAR(500) DEFAULT NULL COMMENT '流程描述',
    `model_xml` LONGTEXT COMMENT '流程模型XML内容',
    `diagram_svg` LONGTEXT COMMENT '流程图SVG',
    `version` INT DEFAULT 1 COMMENT '流程版本',
    `status` TINYINT DEFAULT 0 COMMENT '状态（0:草稿 1:已发布 2:已停用）',
    `form_type` TINYINT DEFAULT 0 COMMENT '表单类型（0:自定义表单 1:在线表单）',
    `form_id` BIGINT DEFAULT NULL COMMENT '表单ID',
    `tenant_id` BIGINT DEFAULT NULL COMMENT '租户ID',
    `is_multi_instance` TINYINT DEFAULT 0 COMMENT '是否多实例（0:否 1:是）',
    `timeout_remind` INT DEFAULT 0 COMMENT '超时提醒设置（小时）',
    `icon` VARCHAR(200) DEFAULT NULL COMMENT '流程图标',
    `sort_order` INT DEFAULT 0 COMMENT '排序号',
    `flowable_definition_id` VARCHAR(100) DEFAULT NULL COMMENT 'Flowable流程定义ID',
    `deployment_id` VARCHAR(100) DEFAULT NULL COMMENT '部署ID',
    `deleted` TINYINT DEFAULT 0 COMMENT '删除标志（0:未删除 1:已删除）',
    `create_by` BIGINT DEFAULT NULL COMMENT '创建人',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_by` BIGINT DEFAULT NULL COMMENT '更新人',
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_process_key` (`process_key`),
    KEY `idx_status` (`status`),
    KEY `idx_tenant_id` (`tenant_id`),
    KEY `idx_flowable_definition_id` (`flowable_definition_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='流程定义表';

-- 流程实例表
CREATE TABLE IF NOT EXISTS `workflow_instance` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    `definition_id` BIGINT NOT NULL COMMENT '流程定义ID',
    `process_instance_id` VARCHAR(100) NOT NULL COMMENT 'Flowable流程实例ID',
    `business_type` VARCHAR(100) DEFAULT NULL COMMENT '业务类型',
    `business_key` VARCHAR(200) DEFAULT NULL COMMENT '业务Key',
    `business_title` VARCHAR(500) DEFAULT NULL COMMENT '业务标题',
    `applicant_id` BIGINT NOT NULL COMMENT '申请人ID',
    `applicant_name` VARCHAR(100) DEFAULT NULL COMMENT '申请人姓名',
    `dept_id` BIGINT DEFAULT NULL COMMENT '申请人部门ID',
    `dept_name` VARCHAR(100) DEFAULT NULL COMMENT '申请人部门名称',
    `status` TINYINT DEFAULT 0 COMMENT '流程状态（0:运行中 1:已完成 2:已终止 3:已挂起）',
    `result` TINYINT DEFAULT 0 COMMENT '流程结果（0:审批中 1:通过 2:驳回 3:撤回）',
    `start_time` DATETIME DEFAULT NULL COMMENT '开始时间',
    `end_time` DATETIME DEFAULT NULL COMMENT '结束时间',
    `duration` BIGINT DEFAULT NULL COMMENT '持续时间（毫秒）',
    `current_node_id` VARCHAR(100) DEFAULT NULL COMMENT '当前节点ID',
    `current_node_name` VARCHAR(200) DEFAULT NULL COMMENT '当前节点名称',
    `current_assignee_id` BIGINT DEFAULT NULL COMMENT '当前处理人ID',
    `current_assignee_name` VARCHAR(100) DEFAULT NULL COMMENT '当前处理人姓名',
    `form_data` JSON DEFAULT NULL COMMENT '表单数据JSON',
    `variables` JSON DEFAULT NULL COMMENT '流程变量JSON',
    `tenant_id` BIGINT DEFAULT NULL COMMENT '租户ID',
    `remark` VARCHAR(500) DEFAULT NULL COMMENT '备注',
    `deleted` TINYINT DEFAULT 0 COMMENT '删除标志（0:未删除 1:已删除）',
    `create_by` BIGINT DEFAULT NULL COMMENT '创建人',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_by` BIGINT DEFAULT NULL COMMENT '更新人',
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_definition_id` (`definition_id`),
    KEY `idx_process_instance_id` (`process_instance_id`),
    KEY `idx_business_key` (`business_key`),
    KEY `idx_applicant_id` (`applicant_id`),
    KEY `idx_status` (`status`),
    KEY `idx_tenant_id` (`tenant_id`),
    KEY `idx_create_time` (`create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='流程实例表';

-- 流程任务表
CREATE TABLE IF NOT EXISTS `workflow_task` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    `instance_id` BIGINT NOT NULL COMMENT '流程实例ID',
    `task_id` VARCHAR(100) NOT NULL COMMENT 'Flowable任务ID',
    `definition_id` BIGINT DEFAULT NULL COMMENT '流程定义ID',
    `node_id` VARCHAR(100) DEFAULT NULL COMMENT '节点ID',
    `node_name` VARCHAR(200) DEFAULT NULL COMMENT '节点名称',
    `task_type` TINYINT DEFAULT 0 COMMENT '任务类型（0:审批任务 1:抄送任务 2:办理任务）',
    `assignee_id` BIGINT DEFAULT NULL COMMENT '处理人ID',
    `assignee_name` VARCHAR(100) DEFAULT NULL COMMENT '处理人姓名',
    `candidate_ids` VARCHAR(500) DEFAULT NULL COMMENT '候选人ID列表（逗号分隔）',
    `candidate_groups` VARCHAR(500) DEFAULT NULL COMMENT '候选组',
    `status` TINYINT DEFAULT 0 COMMENT '任务状态（0:待处理 1:已处理 2:已转办 3:已委派）',
    `result` TINYINT DEFAULT 0 COMMENT '审批结果（0:待审批 1:通过 2:驳回 3:转办 4:委派 5:撤回）',
    `comment` VARCHAR(1000) DEFAULT NULL COMMENT '审批意见',
    `form_data` JSON DEFAULT NULL COMMENT '表单数据JSON',
    `arrive_time` DATETIME DEFAULT NULL COMMENT '到达时间',
    `handle_time` DATETIME DEFAULT NULL COMMENT '处理时间',
    `duration` BIGINT DEFAULT NULL COMMENT '持续时间（毫秒）',
    `due_time` DATETIME DEFAULT NULL COMMENT '超时时间',
    `is_read` TINYINT DEFAULT 0 COMMENT '是否已读（0:未读 1:已读）',
    `read_time` DATETIME DEFAULT NULL COMMENT '阅读时间',
    `parent_task_id` BIGINT DEFAULT NULL COMMENT '父任务ID',
    `tenant_id` BIGINT DEFAULT NULL COMMENT '租户ID',
    `deleted` TINYINT DEFAULT 0 COMMENT '删除标志（0:未删除 1:已删除）',
    `create_by` BIGINT DEFAULT NULL COMMENT '创建人',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_by` BIGINT DEFAULT NULL COMMENT '更新人',
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_instance_id` (`instance_id`),
    KEY `idx_task_id` (`task_id`),
    KEY `idx_assignee_id` (`assignee_id`),
    KEY `idx_status` (`status`),
    KEY `idx_tenant_id` (`tenant_id`),
    KEY `idx_arrive_time` (`arrive_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='流程任务表';

