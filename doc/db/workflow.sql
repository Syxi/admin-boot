    `pass_rate` INT DEFAULT 100 COMMENT '审批通过比例',
    `allow_transfer` TINYINT DEFAULT 1 COMMENT '是否允许转办（0:否 1:是）',
    `allow_delegate` TINYINT DEFAULT 1 COMMENT '是否允许委派（0:否 1:是）',
    `allow_add_sign` TINYINT DEFAULT 0 COMMENT '是否允许加签（0:否 1:是）',
    `allow_back` TINYINT DEFAULT 1 COMMENT '是否允许退回（0:否 1:是）',
    `back_type` TINYINT DEFAULT 1 COMMENT '退回方式（1:退回上一步 2:退回发起人 3:自由选择）',
    `require_comment` TINYINT DEFAULT 0 COMMENT '是否必填意见（0:否 1:是）',
    `allow_cc` TINYINT DEFAULT 1 COMMENT '是否允许抄送（0:否 1:是）',
    `cc_user_ids` VARCHAR(500) DEFAULT NULL COMMENT '抄送人IDs',
    `timeout_hours` INT DEFAULT 0 COMMENT '超时提醒设置（小时）',
    `form_permissions` JSON DEFAULT NULL COMMENT '表单权限配置JSON',
    `button_permissions` JSON DEFAULT NULL COMMENT '按钮权限配置JSON',
    `condition_expression` VARCHAR(500) DEFAULT NULL COMMENT '条件表达式',
    `sort_order` INT DEFAULT 0 COMMENT '排序号',
    `tenant_id` BIGINT DEFAULT NULL COMMENT '租户ID',
    `deleted` TINYINT DEFAULT 0 COMMENT '删除标志（0:未删除 1:已删除）',
    `create_by` BIGINT DEFAULT NULL COMMENT '创建人',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_by` BIGINT DEFAULT NULL COMMENT '更新人',
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_definition_id` (`definition_id`),
    KEY `idx_node_id` (`node_id`),
    KEY `idx_tenant_id` (`tenant_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='流程节点配置表';

-- 流程回调记录表
CREATE TABLE IF NOT EXISTS `workflow_callback` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    `instance_id` BIGINT NOT NULL COMMENT '流程实例ID',
    `business_type` VARCHAR(100) DEFAULT NULL COMMENT '业务类型',
    `business_key` VARCHAR(200) DEFAULT NULL COMMENT '业务Key',
    `callback_type` TINYINT NOT NULL COMMENT '回调类型（1:流程开始 2:流程结束 3:节点进入 4:节点完成 5:任务分配 6:审批结果）',
    `callback_url` VARCHAR(500) DEFAULT NULL COMMENT '回调URL',
    `callback_data` JSON DEFAULT NULL COMMENT '回调数据JSON',
    `status` TINYINT DEFAULT 0 COMMENT '回调状态（0:待发送 1:发送成功 2:发送失败）',
    `retry_count` INT DEFAULT 0 COMMENT '发送次数',
    `max_retry` INT DEFAULT 3 COMMENT '最大重试次数',
    `response_result` TEXT DEFAULT NULL COMMENT '响应结果',
    `send_time` DATETIME DEFAULT NULL COMMENT '发送时间',
    `tenant_id` BIGINT DEFAULT NULL COMMENT '租户ID',
    `deleted` TINYINT DEFAULT 0 COMMENT '删除标志（0:未删除 1:已删除）',
    `create_by` BIGINT DEFAULT NULL COMMENT '创建人',
    `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_by` BIGINT DEFAULT NULL COMMENT '更新人',
    `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_instance_id` (`instance_id`),
    KEY `idx_callback_type` (`callback_type`),
    KEY `idx_status` (`status`),
    KEY `idx_tenant_id` (`tenant_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='流程回调记录表';

